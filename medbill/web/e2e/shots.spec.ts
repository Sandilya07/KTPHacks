import { test } from '@playwright/test'

// Visual check helper: saves screenshots of each screen to $SHOTS (skipped unless set).
test('screens', async ({ page }, info) => {
  const dir = process.env.SHOTS
  test.skip(!dir, 'set SHOTS to a folder to capture screenshots')
  const shot = (n: string) => page.screenshot({ path: `${dir}/${info.project.name}-${n}.png`, fullPage: true })
  await page.goto('/')
  await shot('1-welcome')
  await page.getByRole('button', { name: 'Get started' }).click()
  await shot('2-upload')
  await page.getByTestId('sample-overcharge_photo').click()
  await page.getByRole('heading', { name: 'Check what we read' }).waitFor()
  await page.getByLabel('You owe').last().focus()
  await page.waitForTimeout(500)
  await shot('3-review')
  await page.getByTestId('looks-right').click()
  await page.getByTestId('headline').waitFor()
  await page.getByTestId('evidence-eob_mismatch').click()
  await page.waitForTimeout(700)
  await shot('4-results')
  await page.getByRole('button', { name: 'Ask a question' }).click()
  await page.getByRole('button', { name: 'How much do I actually owe?' }).click()
  await page.getByTestId('msg-assistant').first().waitFor()
  await page.getByRole('button', { name: 'Why was I charged twice?' }).click()
  await page.getByTestId('msg-assistant').nth(1).waitFor()
  await shot('5-ask')
  await page.getByRole('button', { name: 'Write the letter' }).click()
  await page.getByTestId('letter-english').waitFor()
  await shot('6-letter')
})
