import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'

async function sampleResults(page: Page) {
  await page.goto('/')
  await page.getByTestId('welcome-example').click()
  await expect(page.getByRole('heading', { name: 'Check what we read', exact: true })).toBeVisible()
  await page.getByTestId('looks-right').click()
  await page.getByTestId('headline').waitFor()
}

test('sample shortcut, comparison, certainty filters, correction sandbox and report export', async ({ page }) => {
  await sampleResults(page)
  const comparison = page.getByTestId('comparison')
  await expect(comparison).toContainText('$502.00')
  await expect(comparison).toContainText('$90.00')
  await expect(comparison).toContainText('4 of 5 bill lines matched')
  await comparison.locator('summary').click()
  await expect(comparison.locator('.comparison-row')).toHaveCount(5)
  await comparison.getByRole('button', { name: 'View line B5', exact: true }).click()
  await expect(page.getByTestId('highlight-B5')).toBeVisible()

  const filters = page.getByRole('group', { name: 'Filter findings' })
  await filters.getByRole('button', { name: /^Definite/ }).click()
  await expect(page.locator('article')).toHaveCount(2)
  await filters.getByRole('button', { name: /^Likely/ }).click()
  await expect(page.locator('article')).toHaveCount(1)
  await filters.getByRole('button', { name: /^All findings/ }).click()
  await expect(page.locator('article')).toHaveCount(3)

  await page.getByTestId('correction-tool').locator('summary').click()
  await page.getByLabel('Bill line to explore').selectOption('B5')
  await page.getByLabel('Proposed patient charge').fill('40')
  await page.getByRole('button', { name: 'Preview correction', exact: true }).click()
  const preview = page.getByTestId('correction-result')
  await expect(preview).toContainText('$295.00')
  await expect(preview).toContainText('$205.00')
  await expect(preview).toContainText('Resolved findings in this scenario: 1')
  await expect(page.getByTestId('headline')).toContainText('$412.00')
  await expect(comparison).toContainText('$502.00')
  const download = page.waitForEvent('download')
  await page.getByTestId('download-report').click()
  expect((await download).suggestedFilename()).toBe('medbill-evidence-report.pdf')
  expect(await (await download).failure()).toBeNull()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(0)
})

test('preview and export failures preserve the original review', async ({ page }) => {
  await sampleResults(page)
  await page.route('**/api/cases/*/preview', (route) => route.fulfill({ status: 422, json: { detail: 'Please review that proposed amount.' } }))
  await page.getByTestId('correction-tool').locator('summary').click()
  await page.getByRole('button', { name: 'Preview correction', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Please review that proposed amount.')
  await expect(page.getByTestId('headline')).toContainText('$412.00')
  await page.route('**/api/cases/*/report', (route) => route.fulfill({ status: 503, json: { detail: 'The report is temporarily unavailable.' } }))
  await page.getByTestId('download-report').click()
  await expect(page.getByRole('alert').last()).toContainText('The report is temporarily unavailable.')
  await expect(page.getByRole('heading', { name: 'Results', exact: true })).toBeVisible()
})

test('expanded comparison and correction preview remain accessible', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await sampleResults(page)
  await page.getByTestId('comparison').locator('summary').click()
  await page.getByTestId('correction-tool').locator('summary').click()
  await page.getByRole('button', { name: 'Preview correction', exact: true }).click()
  await page.getByTestId('correction-result').waitFor()
  const report = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  expect(report.violations.filter((issue) => issue.impact === 'critical' || issue.impact === 'serious')
    .map((issue) => ({ rule: issue.id, nodes: issue.nodes.map((node) => node.html) }))).toEqual([])
})

test('new review tools follow the detected Spanish interface language', async ({ page }) => {
  await page.goto('/')
  await page.locator('#language-text').fill('Quiero entender mi factura')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'es')
  await page.getByTestId('welcome-example').click()
  await page.getByTestId('looks-right').click()
  await page.getByTestId('headline').waitFor()
  await expect(page.getByTestId('comparison')).toContainText('Su factura, lado a lado')
  await page.getByTestId('correction-tool').locator('summary').click()
  await page.getByRole('button', { name: 'Ver corrección propuesta', exact: true }).click()
  await expect(page.getByTestId('correction-result')).toContainText('$205.00')
  await expect(page.getByTestId('download-report')).toHaveText('Descargar informe de evidencia')
})
